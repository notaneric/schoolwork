# -*- coding: utf-8 -*-
"""Verifies the 2026-10-02 D2L package update (migration flag fall2026_oct2_v11).

Why five device states and not one:
  localStorage beats seed() once a device has state, so a "fresh" pass proves only that the seed
  is right. migrate() is what reaches Eric's real browser, and the only honest way to exercise it
  is to generate state with the PREVIOUS page and then load the new one over it.

  [1] fresh     - no stored state. Exercises seed().
  [2] existing  - state written by the pre-change page. Exercises migrate().
  [3] edited    - the same, with two fields changed the way Eric would change them. Proves the
                  guards leave his own edits alone.
  [4] guardset  - NEGATIVE CONTROL. Pre-sets meta.fall2026_oct2_v11 on old state so the migration
                  cannot run. If the Oct 7 assertions still passed here they would be reading the
                  seed and proving nothing about the migration.
  [5] twice     - migrated state reloaded. Proves nothing duplicates.

Usage:  python tools/verify_oct2_v11.py            (derives old page from git HEAD)
        python tools/verify_oct2_v11.py <old.html>
"""
import json, os, subprocess, sys, tempfile
from playwright.sync_api import sync_playwright

KEY = "boris_school_fall2026"
FLAG = "fall2026_oct2_v11"
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
# SCHOOLWORK_PAGE lets the mutation harness point this at a mutated COPY. The live file is never
# edited to test a check (S180: a mutant run into a live folder was read back as the real document).
PAGE = os.environ.get("SCHOOLWORK_PAGE") or os.path.join(REPO, "index.html")
NEW = "file:///" + os.path.abspath(PAGE).replace("\\", "/").replace(" ", "%20")

OLD_DUE = "2026-10-05T23:59:00-04:00"
NEW_DUE = "2026-10-07T23:59:00-04:00"
MOVED = ["chem1211-knewton-3-4-7", "chem1211-ps3-part2"]
ADDED = ["chem1211-ch3-video-assignment", "sci2900-henrietta-lacks", "sci2900-lit-review"]

_pass, _fails = 0, []


def ok(name, cond, extra=None):
    global _pass
    if cond:
        _pass += 1
        print("  PASS  " + name)
    else:
        _fails.append(name)
        print("  FAIL  " + name + ("  -> " + json.dumps(extra, ensure_ascii=False) if extra is not None else ""))


def old_page_path():
    if len(sys.argv) > 1:
        return sys.argv[1]
    blob = subprocess.run(["git", "-C", REPO, "show", "HEAD:index.html"],
                          capture_output=True, check=True).stdout
    fd, p = tempfile.mkstemp(suffix="-old-index.html")
    os.write(fd, blob)
    os.close(fd)
    return p


class Loaded(object):
    def __init__(self, ctx, url, state):
        self.errs = []
        self.page = ctx.new_page()
        self.page.on("pageerror", lambda e: self.errs.append(str(e)))
        self.page.on("console", lambda m: self.errs.append(m.text) if m.type == "error" else None)
        if state is not None:
            self.page.add_init_script("(() => { localStorage.setItem(%s, %s); })()"
                                      % (json.dumps(KEY), json.dumps(state)))
        self.page.goto(url)
        self.page.wait_for_timeout(400)

    def raw(self):
        return self.page.evaluate("k => localStorage.getItem(k)", KEY)

    def db(self):
        return json.loads(self.raw())

    def panel(self, title):
        return self.page.evaluate("""t => {
            const h = Array.from(document.querySelectorAll('.section-header')).find(x => x.textContent.includes(t));
            if (!h) return null;
            let n = h.nextElementSibling;
            while (n && !n.classList.contains('assignment-list')) n = n.nextElementSibling;
            return n ? n.textContent : null;
        }""", title)

    def close(self):
        self.page.close()


def find(db, iid):
    for a in db["assignments"]:
        if a["id"] == iid:
            return a
    return None


def main():
    oldp = old_page_path()
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        ctx = browser.new_context()
        old_url = "file:///" + os.path.abspath(oldp).replace("\\", "/").replace(" ", "%20")

        print("\n[0] state generated by the pre-change page")
        o = Loaded(ctx, old_url, None)
        old_state = o.raw()
        old_db = json.loads(old_state)
        ok("old page stores state at all", bool(old_state))
        ok("old page has NO " + FLAG, not old_db["meta"].get(FLAG))
        ok("old page carries the Oct 5 deadline (the defect being fixed)",
           all(find(old_db, i)["dueDate"] == OLD_DUE for i in MOVED),
           [find(old_db, i)["dueDate"] for i in MOVED])
        ok("old page lacks all 3 new items", all(find(old_db, i) is None for i in ADDED))
        o.close()

        print("\n[1] fresh device (seed)")
        p = Loaded(ctx, NEW, None)
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("3 new items seeded", all(find(db, i) for i in ADDED), [i for i in ADDED if not find(db, i)])
        ok("both moved items read Oct 7", all(find(db, i)["dueDate"] == NEW_DUE for i in MOVED))
        ok("video assignment due Oct 5 at 10:00",
           find(db, "chem1211-ch3-video-assignment")["dueDate"] == "2026-10-05T10:00:00-04:00")
        ok("both SCI items carry dueDate null (no invented date)",
           all(find(db, i)["dueDate"] is None for i in ["sci2900-henrietta-lacks", "sci2900-lit-review"]))
        ok("Chapter 4 topic moved off the cancelled Oct 2",
           [t for t in db["topics"] if t["id"] == "chem1211-ch4"][0]["startsDate"] == "2026-10-05")
        und = p.panel("Deadline unknown")
        ok("both dateless SCI items render in the Deadline-unknown panel",
           bool(und) and "Henrietta Lacks" in und and "Primary Literature Review" in und)
        com = p.panel("Coming Up")
        ok("video assignment renders in Coming Up", bool(com) and "Chapter 3 Video Assignment" in com)
        # Two traps here, both found by mutation. body.textContent also reads the <script> source,
        # where the old string legitimately survives as a migration guard constant - so scripts are
        # stripped. And only one view is in the DOM at a time, so a stale date in the Resources tab
        # or the instructor intel is invisible until that view is rendered - so all six are swept.
        stale = p.page.evaluate("""() => {
            const views = ['dashboard','list','calendar','courses','instructors','resources'];
            const hits = [];
            for (const v of views) {
              setView(v);
              const c = document.getElementById('content-area').cloneNode(true);
              c.querySelectorAll('script,style').forEach(n => n.remove());
              const t = c.textContent;
              for (const bad of ['all due Mon Oct 5', 'due Mon Oct 5', 'due Oct 5'])
                if (t.includes(bad)) hits.push(v + ': ' + bad);
            }
            setView('dashboard');
            return hits;
        }""")
        ok("no view states the Chapter 3 Part 2 deadline as Oct 5 (all 6 views swept)", not stale, stale)
        p.close()

        print("\n[2] existing device (migration over pre-change state)")
        p = Loaded(ctx, NEW, old_state)
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("migration flag set", db["meta"].get(FLAG) is True)
        ok("3 new items merged in", all(find(db, i) for i in ADDED), [i for i in ADDED if not find(db, i)])
        ok("Oct 5 deadline corrected to Oct 7", all(find(db, i)["dueDate"] == NEW_DUE for i in MOVED),
           [find(db, i)["dueDate"] for i in MOVED])
        ok("moved notes now say DEADLINE MOVED", all("DEADLINE MOVED" in find(db, i)["notes"] for i in MOVED))
        ok("ps3-part1 stale forward reference rewritten",
           "moved to Wed Oct 7" in find(db, "chem1211-ps3-part1")["notes"])
        ok("oral presentation notes pick up the literature review",
           "entire basis of your final" in find(db, "sci2900-oral-presentation")["notes"])
        ok("Chapter 4 topic startsDate migrated",
           [t for t in db["topics"] if t["id"] == "chem1211-ch4"][0]["startsDate"] == "2026-10-05")
        ok("Chapter 3 pt 2 topic title migrated",
           "Wed Oct 7" in [t for t in db["topics"] if t["id"] == "chem1211-ch3-2"][0]["title"])
        ok("nothing pre-existing was dropped",
           all(find(db, a["id"]) for a in old_db["assignments"])
           and len(db["assignments"]) == len(old_db["assignments"]) + 3,
           [len(old_db["assignments"]), len(db["assignments"])])
        migrated_state = p.raw()
        p.close()

        print("\n[3] user-edited device (guards)")
        ed = json.loads(old_state)
        find(ed, "chem1211-knewton-3-4-7")["dueDate"] = "2026-10-06T08:00:00-04:00"
        find(ed, "chem1211-knewton-3-4-7")["status"] = "submitted"
        find(ed, "sci2900-oral-presentation")["notes"] = "my own note, do not touch"
        p = Loaded(ctx, NEW, json.dumps(ed))
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("his edited dueDate survives", find(db, "chem1211-knewton-3-4-7")["dueDate"] == "2026-10-06T08:00:00-04:00")
        ok("his status survives", find(db, "chem1211-knewton-3-4-7")["status"] == "submitted")
        ok("his rewritten notes survive", find(db, "sci2900-oral-presentation")["notes"] == "my own note, do not touch")
        ok("the untouched sibling still gets corrected", find(db, "chem1211-ps3-part2")["dueDate"] == NEW_DUE)
        ok("new items still arrive", all(find(db, i) for i in ADDED))
        p.close()

        print("\n[4] negative control (flag pre-set, migration must NOT run)")
        bl = json.loads(old_state)
        bl["meta"][FLAG] = True
        p = Loaded(ctx, NEW, json.dumps(bl))
        db = p.db()
        ok("CONTROL: deadline stays Oct 5 when the migration is blocked",
           all(find(db, i)["dueDate"] == OLD_DUE for i in MOVED), [find(db, i)["dueDate"] for i in MOVED])
        ok("CONTROL: no new item appears when the migration is blocked",
           all(find(db, i) is None for i in ADDED), [i for i in ADDED if find(db, i)])
        p.close()

        print("\n[5] reload of migrated state")
        p = Loaded(ctx, NEW, migrated_state)
        db = p.db()
        ok("no duplicate assignment ids", len(set(a["id"] for a in db["assignments"])) == len(db["assignments"]))
        ok("no duplicate topic ids", len(set(t["id"] for t in db["topics"])) == len(db["topics"]))
        ok("count unchanged on reload", len(db["assignments"]) == len(old_db["assignments"]) + 3)
        p.close()

        browser.close()

    print("\n%d passed, %d failed" % (_pass, len(_fails)))
    if _fails:
        for f in _fails:
            print("  FAILED: " + f)
        sys.exit(1)


if __name__ == "__main__":
    main()
