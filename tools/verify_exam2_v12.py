# -*- coding: utf-8 -*-
"""Verifies the 2026-10-11 CHEM export update (migration flag chem1211_exam2_v12).

Same five device states as verify_oct2_v11.py, built from the PREVIOUS page (git HEAD), plus a sixth:
  [6] chain - state written by the pre-v10 page (commit f223530), so v10, v11 and v12 all run in one
              load. v10 and v11 rewrite the Exam 2 notes and the Chapter 4 title from their own old
              values to whatever the CURRENT seed says, so this proves an older device lands on the
              v12 text and not on an intermediate one.

Usage:  python tools/verify_exam2_v12.py
        SCHOOLWORK_PAGE=<copy.html> python tools/verify_exam2_v12.py   (mutation runs)
"""
import json, os, subprocess, sys, tempfile
from playwright.sync_api import sync_playwright

KEY = "boris_school_fall2026"
FLAG = "chem1211_exam2_v12"
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PAGE = os.environ.get("SCHOOLWORK_PAGE") or os.path.join(REPO, "index.html")
NEW = "file:///" + os.path.abspath(PAGE).replace("\\", "/").replace(" ", "%20")
CHAIN_REV = "f223530"   # last commit before the v10 migration existed

ADDED = {"chem1211-knewton-4-1-3": "2026-10-12T23:59:00-04:00",
         "chem1211-ps5-ch4-part1": "2026-10-12T23:59:00-04:00",
         "chem1211-ch3-worksheet": "2026-10-14T10:00:00-04:00",
         "chem1211-ch4-worksheet": "2026-10-14T10:00:00-04:00"}
OLD_EX2 = "Covers the rest of Chapter 3, Chapter 4 (bonding and molecular geometry), and Chapter 10"
NEW_EX2 = "SCOPE IS SET: the study guide posted Fri Oct 9"

_pass, _fails = 0, []


def ok(name, cond, extra=None):
    global _pass
    if cond:
        _pass += 1
        print("  PASS  " + name)
    else:
        _fails.append(name)
        print("  FAIL  " + name + ("  -> " + json.dumps(extra, ensure_ascii=False)[:300] if extra is not None else ""))


def page_from_git(rev):
    blob = subprocess.run(["git", "-C", REPO, "show", rev + ":index.html"], capture_output=True, check=True).stdout
    fd, p = tempfile.mkstemp(suffix="-%s-index.html" % rev.replace(":", ""))
    os.write(fd, blob)
    os.close(fd)
    return "file:///" + p.replace("\\", "/").replace(" ", "%20")


class Loaded(object):
    def __init__(self, browser, url, state):
        # One isolated context per device. A shared context shares file:// localStorage, so a
        # 'fresh' device would inherit the previous device's state (found by mutation, S206).
        self.errs = []
        self.ctx = browser.new_context()
        self.page = self.ctx.new_page()
        self.page.on("pageerror", lambda e: self.errs.append(str(e)))
        self.page.on("console", lambda m: self.errs.append(m.text) if m.type == "error" else None)
        if state is not None:
            self.page.add_init_script("(() => { if (!sessionStorage.getItem('seeded')) { localStorage.setItem(%s, %s); sessionStorage.setItem('seeded','1'); } })()"
                                      % (json.dumps(KEY), json.dumps(state)))
        self.page.goto(url)
        self.page.wait_for_timeout(400)

    def raw(self):
        return self.page.evaluate("k => localStorage.getItem(k)", KEY)

    def db(self):
        return json.loads(self.raw())

    def view_text(self, view):
        return self.page.evaluate("""v => { setView(v); const c = document.getElementById('content-area').cloneNode(true);
            c.querySelectorAll('script,style').forEach(n => n.remove()); const t = c.textContent; setView('dashboard'); return t; }""", view)

    def close(self):
        self.page.close()
        self.ctx.close()


def find(db, iid):
    return next((a for a in db["assignments"] if a["id"] == iid), None)


def topic(db, tid):
    return next((t for t in db["topics"] if t["id"] == tid), None)


def main():
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        ctx = browser

        print("\n[0] state generated by the pre-change page (git HEAD)")
        o = Loaded(ctx, page_from_git("HEAD"), None)
        old_state = o.raw()
        old_db = json.loads(old_state)
        ok("old page has NO " + FLAG, not old_db["meta"].get(FLAG))
        ok("old page carries the syllabus Exam 2 scope (the defect being fixed)",
           find(old_db, "chem1211-exam2")["notes"].startswith(OLD_EX2))
        ok("old page lacks all 4 new items", all(find(old_db, i) is None for i in ADDED))
        o.close()

        print("\n[1] fresh device (seed)")
        p = Loaded(ctx, NEW, None)
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("4 new items seeded with their dates", all(find(db, i) and find(db, i)["dueDate"] == d for i, d in ADDED.items()))
        ok("Exam 2 notes carry the study-guide scope", find(db, "chem1211-exam2")["notes"].startswith(NEW_EX2))
        ok("Chapter 4 topic says it opened Oct 5", "Opened Mon Oct 5" in topic(db, "chem1211-ch4")["title"])
        ok("Chapter 10 marker flags its date as wrong", "it is wrong" in topic(db, "chem1211-ch10")["title"])
        dash = p.view_text("dashboard")
        ok("dashboard shows the Oct 12 Knewton group", "Knewton 4.1" in dash)
        sweep = {}
        for v in ["dashboard", "list", "calendar", "courses", "instructors", "resources"]:
            t = p.view_text(v)
            for bad in ["expect Chapter 10 to be the part that goes", "Exam 2 still reads", "94 questions and 54 terms",
                        "DUE WED OCT 7", "DUE SEP 25"]:
                if bad in t:
                    sweep.setdefault(v, []).append(bad)
        ok("no view still states a superseded scope, deadline or count (6 views swept)", not sweep, sweep)
        res = p.view_text("resources")
        ok("Resources carries the Exam 2 group and study-set launcher",
           "Exam 2: Wed Oct 14" in res and "CHEM 1211 Exam 2 Study Set" in res)
        ok("launcher points at chem1211-exam2-study.html",
           p.page.evaluate("() => { setView('resources'); const a = document.querySelector('a[href=\"chem1211-exam2-study.html\"]'); setView('dashboard'); return !!a; }"))
        intel = p.view_text("instructors")
        ok("instructor intel names the Oct 12 deadline and the Exam 2 scope", "DUE MON OCT 12" in intel and "EXAM 2 WED OCT 14" in intel)
        p.close()

        print("\n[2] existing device (migration over HEAD state)")
        p = Loaded(ctx, NEW, old_state)
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("migration flag set", db["meta"].get(FLAG) is True)
        ok("4 new items merged in", all(find(db, i) for i in ADDED), [i for i in ADDED if not find(db, i)])
        ok("Exam 2 notes migrated", find(db, "chem1211-exam2")["notes"].startswith(NEW_EX2))
        ok("Chapter 4 title migrated", "Opened Mon Oct 5" in topic(db, "chem1211-ch4")["title"])
        ok("Chapter 10 title migrated", "it is wrong" in topic(db, "chem1211-ch10")["title"])
        ok("nothing dropped, exactly 4 added",
           all(find(db, a["id"]) for a in old_db["assignments"]) and len(db["assignments"]) == len(old_db["assignments"]) + 4,
           [len(old_db["assignments"]), len(db["assignments"])])
        migrated = p.raw()
        p.close()

        print("\n[3] user-edited device (guards)")
        ed = json.loads(old_state)
        find(ed, "chem1211-exam2")["notes"] = "my own exam note"
        find(ed, "chem1211-exam2")["status"] = "submitted"
        topic(ed, "chem1211-ch4")["title"] = "Ch 4, my title"
        p = Loaded(ctx, NEW, json.dumps(ed))
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("his Exam 2 note survives", find(db, "chem1211-exam2")["notes"] == "my own exam note")
        ok("his Exam 2 status survives", find(db, "chem1211-exam2")["status"] == "submitted")
        ok("his Chapter 4 title survives", topic(db, "chem1211-ch4")["title"] == "Ch 4, my title")
        ok("the untouched Chapter 10 title still migrates", "it is wrong" in topic(db, "chem1211-ch10")["title"])
        ok("new items still arrive", all(find(db, i) for i in ADDED))
        p.close()

        print("\n[4] negative control (flag pre-set, migration must NOT run)")
        bl = json.loads(old_state)
        bl["meta"][FLAG] = True
        p = Loaded(ctx, NEW, json.dumps(bl))
        db = p.db()
        ok("CONTROL: Exam 2 notes stay on the syllabus scope", find(db, "chem1211-exam2")["notes"].startswith(OLD_EX2))
        ok("CONTROL: no new item appears", all(find(db, i) is None for i in ADDED))
        p.close()

        print("\n[5] reload of migrated state")
        p = Loaded(ctx, NEW, migrated)
        db = p.db()
        ok("no duplicate assignment ids", len(set(a["id"] for a in db["assignments"])) == len(db["assignments"]))
        ok("no duplicate topic ids", len(set(t["id"] for t in db["topics"])) == len(db["topics"]))
        ok("count unchanged on reload", len(db["assignments"]) == len(old_db["assignments"]) + 4)
        p.close()

        print("\n[6] chain: pre-v10 device runs v10, v11 and v12 in one load")
        o = Loaded(ctx, page_from_git(CHAIN_REV), None)
        chain_state = o.raw()
        o.close()
        p = Loaded(ctx, NEW, chain_state)
        db = p.db()
        ok("no JS errors", not p.errs, p.errs)
        ok("all three flags set", all(db["meta"].get(f) for f in ["chem1211_ch3_part2_v10", "fall2026_oct2_v11", FLAG]))
        ok("Exam 2 notes land on v12 text", find(db, "chem1211-exam2")["notes"].startswith(NEW_EX2))
        ok("Chapter 4 title lands on v12 text", "Opened Mon Oct 5" in topic(db, "chem1211-ch4")["title"])
        ok("v12 items present", all(find(db, i) for i in ADDED))
        p.close()

        browser.close()

    print("\n%d passed, %d failed" % (_pass, len(_fails)))
    if _fails:
        for f in _fails:
            print("  FAILED: " + f)
        sys.exit(1)


if __name__ == "__main__":
    main()
